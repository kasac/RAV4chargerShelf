import importlib.abc
import importlib.util
import os
import sys


class _BundleImporter(importlib.abc.MetaPathFinder, importlib.abc.Loader):
    """Serves the rav4shelf package from _SOURCES instead of files."""

    def find_spec(self, fullname, path=None, target=None):
        if fullname == "rav4shelf":
            return importlib.util.spec_from_loader(fullname, self, is_package=True)
        if fullname.startswith("rav4shelf.") and fullname[10:] in _SOURCES:
            return importlib.util.spec_from_loader(fullname, self)
        return None

    def create_module(self, spec):
        return None  # default module object

    def exec_module(self, module):
        key = "__init__" if module.__name__ == "rav4shelf" else module.__name__[10:]
        module.__file__ = "<rav4shelf_rhino.py>/rav4shelf/%s.py" % key
        exec(compile(_SOURCES[key], module.__file__, "exec"), module.__dict__)


def _install():
    """Load the embedded package. Rhino keeps modules between runs, so another
    version (or a repo checkout) is dropped first."""
    pkg = sys.modules.get("rav4shelf")
    if pkg is not None and getattr(pkg, "_BUNDLE_VERSION", None) == BUNDLE_VERSION:
        return
    for name in [n for n in sys.modules if n == "rav4shelf" or n.startswith("rav4shelf.")]:
        del sys.modules[name]
    sys.meta_path[:] = [f for f in sys.meta_path if type(f).__name__ != "_BundleImporter"]
    sys.meta_path.insert(0, _BundleImporter())
    import rav4shelf
    import rav4shelf.params
    rav4shelf.params.EMBEDDED_SPEC = _SPEC_JSON
    rav4shelf._BUNDLE_VERSION = BUNDLE_VERSION


def _export_folder(component):
    if EXPORT_FOLDER:
        return EXPORT_FOLDER
    if component is not None:
        doc = component.OnPingDocument()
        if doc is not None and doc.FilePath:
            return os.path.join(os.path.dirname(doc.FilePath), "rav4shelf_out")
    return ""


def main():
    try:
        import Rhino
    except ImportError:
        print("Run this inside Rhino 8 (ScriptEditor) or a Grasshopper Python 3 Script component.")
        return
    _install()
    from rav4shelf import checks, export, geometry, gh, params

    g = globals()
    component = g["ghenv"].Component if "ghenv" in g else None
    p = params.load_params(MY_VALUES)
    notes = []
    if component is not None:
        values, ignored, notes = gh.read_named_inputs(component, p.spec)
        if values:
            p = p.with_overrides(values, "grasshopper")
        if ignored:
            notes.append("ignored (name is not a parameter): " + ", ".join(ignored))
    d = params.derive(p)
    findings = checks.run_checks(p, d)
    report = [checks.format_report(p, d, findings)] + notes
    doc = Rhino.RhinoDoc.ActiveDoc
    units = export.check_units(doc)
    if units:
        report.append(("WARNING: " if component else "STOP: ") + units)
    if checks.has_errors(findings) or (units and component is None):
        report.append("Nothing built: fix the problems above.")
        _finish(component, report, {}, None, {})
        return
    tol = min(doc.ModelAbsoluteTolerance, geometry.DEFAULT_TOL)

    parts = {}  # name -> (solid to export, solid to show in the car frame)
    if "fit_coupon" in BUILD:
        coupon, method = geometry.build_fit_coupon(p, d, tol)
        parts["fit_coupon"] = (coupon, coupon)
        report.append("fit_coupon: built by %s" % method)
    if "profile_gauge" in BUILD:
        flat, standing, method = geometry.build_profile_gauge(p, d, tol)
        parts["profile_gauge"] = (flat, standing)
        report.append("profile_gauge: built by %s" % method)
    for name, (solid, _) in parts.items():
        report += ["  PROBLEM: " + m for m in geometry.check_solid(solid, name)]
    envelope = geometry.build_envelope(p, d, tol) if "envelope" in BUILD else None
    context = geometry.build_context(p, d) if SHOW_CUBBY else {}

    folder = _export_folder(component)
    if folder and (component is None or g.get("export")):
        for name, (solid, _) in parts.items():
            paths, msgs = export.export_part(name, [solid], folder, ("step", "3mf", "stl"), tol,
                                             doc if component is None else None)
            report += ["  wrote " + x for x in paths] + ["  PROBLEM: " + m for m in msgs]
    elif component is not None and g.get("export"):
        report.append("export: save the .gh file first, or set EXPORT_FOLDER")

    if component is not None and g.get("sliders"):
        groups = [x.strip() for x in (g.get("groups") or "").split(",") if x.strip()]
        report.append("creating %d sliders..." % gh.schedule_slider_bank(component, p, groups))
    if p.placeholders:
        report.append("%d values are not confirmed for your car yet (see the report above)."
                      % len(p.placeholders))
    _finish(component, report, parts, envelope, context)


def _finish(component, report, parts, envelope, context):
    text = "\n".join(report)
    if component is None:  # Rhino: bake to layers
        import Rhino
        from rav4shelf import export
        doc = Rhino.RhinoDoc.ActiveDoc
        for name, geo in context.items():
            export.bake(doc, name, geo)
        for name, (_, shown) in parts.items():
            export.bake(doc, name, [shown])
        if envelope is not None:
            export.bake(doc, "envelope", [envelope])
        doc.Views.Redraw()
        print(text)
        return
    g = globals()  # Grasshopper: fill the outputs that exist on the component
    g["coupon"] = parts.get("fit_coupon", (None, None))[1]
    g["gauge"] = parts.get("profile_gauge", (None, None))[1]
    g["envelope"] = envelope
    g["cubby"] = context.get("cubby", []) + context.get("ports", []) + context.get("phone", [])
    g["report"] = text


if __name__ == "__main__" or "ghenv" in globals():
    main()
