def _check_order(sources) -> None:
    """MODULES is the load order: every module-level relative import must
    name a module listed before it."""
    for i, name in enumerate(MODULES):
        for node in ast.parse(sources[name]).body:
            if isinstance(node, ast.ImportFrom) and node.level == 1:
                deps = [node.module] if node.module else [a.name for a in node.names]
                late = [x for x in deps if x not in MODULES[:i]]
                if late:
                    raise SystemExit("%s imports %s: list it earlier in MODULES" % (name, late))


def render() -> str:
    sources = {}
    for name in MODULES:
        with open(os.path.join(REPO, "src", "rav4shelf", name + ".py"), encoding="utf-8") as f:
            sources[name] = f.read()
    with open(os.path.join(REPO, "params", "default.json"), encoding="utf-8") as f:
        spec_json = f.read()
    digest = hashlib.sha1("".join([sources[n] for n in MODULES] + [spec_json, HEADER, LOADER])
                          .encode("utf-8")).hexdigest()[:10]
    _check_order(sources)
    out = [HEADER % {"version": digest},
           "\nBUNDLE_VERSION = %r\n\n_ORDER = %r\n\n_SOURCES = {\n" % (digest, MODULES)]
    for name in MODULES + ["<spec>"]:
        text = spec_json if name == "<spec>" else sources[name]
        if "'''" in text or text.endswith("\\"):
            raise SystemExit("%s cannot be embedded in a r''' string" % name)
    for name in MODULES:
        out.append("    %r: r'''%s''',\n" % (name, sources[name]))
    out.append("}\n\n_SPEC_JSON = r'''%s'''\n" % spec_json)
    out.append(LOADER)
    return "".join(out)


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render())
    print("wrote " + os.path.relpath(OUT, REPO))
