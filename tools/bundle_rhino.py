def _load(name, key):
    mod = types.ModuleType(name)
    mod.__file__ = "<rav4shelf_rhino.py>/rav4shelf/%s.py" % key
    mod.__package__ = "rav4shelf"
    if key == "__init__":
        mod.__path__ = []  # a package: "from . import x" finds x in sys.modules
    sys.modules[name] = mod
    code = compile(_SOURCES[key], mod.__file__, "exec", dont_inherit=True)
    exec(code, mod.__dict__)
    return mod


